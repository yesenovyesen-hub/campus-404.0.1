const INTENT_PATTERNS = Object.freeze([
  ["ownership", /(?:\bмоя\b|\bмой\b|\bмоё\b|\bмое\b|это\s+моя\s+вещь|я\s+потерял(?:а)?\b|я\s+потерял(?:а)?\s)/u],
  ["location", /где|мест[оа]|нашел|нашла|нашли|находится|локаци|встрет|забрать|отдать/u],
  ["item", /что\s+это|какая|какого\s+цвета|цвет|размер|описани/u],
  ["thanks", /спасибо|благодар|спс|thanks/u],
  ["greeting", /привет|здравств|добрый\s+(?:день|вечер|утро)|хай|hello|hi\b/u],
  ["question", /\?/u]
]);

function normalize(text) {
  return String(text || "").normalize("NFKC").toLocaleLowerCase("ru").replace(/ё/g, "е");
}

export function classifyMessage(text) {
  const normalized = normalize(text);
  for (const [intent, pattern] of INTENT_PATTERNS) {
    if (pattern.test(normalized)) return intent;
  }
  return "unknown";
}

function cardDetails(item) {
  const description = typeof item.description === "string" ? item.description.trim() : "";
  if (description) return description;
  const title = typeof item.title === "string" ? item.title.trim() : "";
  const type = typeof item.type === "string" ? item.type.trim() : "";
  if (title && type && normalize(title) !== normalize(type)) return `${title} (тип: ${type})`;
  if (title || type) return title || type;
  return "дополнительное описание в карточке не указано";
}

function cardLocation(item) {
  const location = typeof item.location === "string" ? item.location.trim() : "";
  if (!location || ["—", "-", "не указано"].includes(normalize(location))) {
    return "место находки в карточке не указано";
  }
  return location;
}

export function getChatReply(text, item, history = []) {
  const persona = getPersona(item);
  const intent = classifyMessage(text);
  const replies = REPLY_BANKS[persona.id]?.[intent] || REPLY_BANKS.detective.unknown;
  const previousSameIntent = history.filter((message) =>
    message.sender === "user" && classifyMessage(message.text) === intent
  ).length;
  const variantIndex = Math.max(0, previousSameIntent - 1) % replies.length;

  return replies[variantIndex]
    .replaceAll("{location}", cardLocation(item))
    .replaceAll("{details}", cardDetails(item));
}
